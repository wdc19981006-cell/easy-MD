"""Retrieve missing upstream Cython sources from the pinned release commit."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import requests

root = Path(__file__).resolve().parent.parent / '.ppi-tools/build/lightdock-0.9.4/lightdock-0.9.4'
response = requests.get('https://api.github.com/repos/lightdock/lightdock/git/ref/tags/0.9.4', timeout=45)
response.raise_for_status()
obj = response.json()['object']
if obj['type'] == 'tag':
    response = requests.get(obj['url'], timeout=45)
    response.raise_for_status()
    obj = response.json()['object']
commit = obj['sha']
if commit != 'eaf05c7c39a3d8fbf715cb74a2dfe2857778107f':
    raise RuntimeError('LightDock 0.9.4 tag no longer matches the reviewed release commit')

def download(path):
    if b'Generated by Cython' not in path.read_bytes()[:300]:
        return None
    rel = path.relative_to(root).with_suffix('.pyx')
    url = f'https://raw.githubusercontent.com/lightdock/lightdock/{commit}/{rel.as_posix()}'
    response = requests.get(url, timeout=60)
    response.raise_for_status()
    output = root / rel
    output.write_bytes(response.content)
    return {'path': rel.as_posix(), 'url': url, 'commit': commit, 'sha256': hashlib.sha256(response.content).hexdigest()}

with ThreadPoolExecutor(max_workers=4) as executor:
    records = [x for x in executor.map(download, root.joinpath('lightdock').rglob('*.c')) if x]
(root / 'cython_sources_provenance.json').write_text(json.dumps(records, indent=2), encoding='utf-8')
print(json.dumps(records, indent=2))
