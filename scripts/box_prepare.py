#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Create a Vina config from a native ligand or explicit box coordinates."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from common import enter_work_dir, get_config, load_config


def read_native_info(path: Path) -> tuple[str, str, str]:
    lines = path.read_text(encoding="utf-8").strip().splitlines()
    if len(lines) < 3:
        raise ValueError(f"Invalid native ligand info: {path}")
    return lines[0].strip(), lines[1].strip(), lines[2].strip()


def ligand_coordinates(
    pdb_path: Path,
    residue_name: str,
    chain: str,
    residue_id: str,
) -> np.ndarray:
    coordinates: list[list[float]] = []
    for line in pdb_path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.startswith("HETATM"):
            continue
        if line[17:20].strip() != residue_name:
            continue
        if line[21:22].strip() != chain:
            continue
        if line[22:26].strip() != residue_id:
            continue
        try:
            coordinates.append(
                [float(line[30:38]), float(line[38:46]), float(line[46:54])]
            )
        except ValueError:
            continue
    if not coordinates:
        raise ValueError(
            f"No atoms found for {residue_name} chain {chain} residue {residue_id}"
        )
    return np.asarray(coordinates, dtype=float)


def calculate_box(
    coordinates: np.ndarray,
    padding: float,
    minimum: float,
    maximum: float,
) -> tuple[np.ndarray, np.ndarray]:
    center = coordinates.mean(axis=0)
    dimensions = coordinates.max(axis=0) - coordinates.min(axis=0)
    sizes = np.clip(dimensions + 2.0 * padding, minimum, maximum)
    return center, sizes


def write_vina_config(
    output_path: Path,
    receptor: str,
    ligand: str,
    center: np.ndarray,
    sizes: np.ndarray,
    docking: dict[str, object],
) -> None:
    text = (
        f"receptor = {receptor}\n"
        f"ligand = {ligand}\n"
        f"center_x = {center[0]:.3f}\n"
        f"center_y = {center[1]:.3f}\n"
        f"center_z = {center[2]:.3f}\n"
        f"size_x = {sizes[0]:.1f}\n"
        f"size_y = {sizes[1]:.1f}\n"
        f"size_z = {sizes[2]:.1f}\n"
        f"num_modes = {int(docking.get('num_modes', 9))}\n"
        f"energy_range = {int(docking.get('energy_range', 3))}\n"
        f"exhaustiveness = {int(docking.get('exhaustiveness', 32))}\n"
    )
    output_path.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a Vina docking box")
    parser.add_argument("--pdb", required=True, help="Original PDB path")
    parser.add_argument(
        "--native-info",
        default="native_ligand_info.txt",
        help="Native ligand info generated by protein_prepare.py",
    )
    parser.add_argument("--work-dir", required=True)
    parser.add_argument("--config", help="Path to easy-md config.yaml")
    parser.add_argument("--output", default="config.txt")
    parser.add_argument("--receptor", default="receptor.pdbqt")
    parser.add_argument("--ligand", default="ligand.pdbqt")
    parser.add_argument("--center", nargs=3, type=float, metavar=("X", "Y", "Z"))
    parser.add_argument("--size", nargs=3, type=float, metavar=("SX", "SY", "SZ"))
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    config = load_config(args.config)
    if args.size and not args.center:
        parser.error("--size requires --center")
    pdb_path = Path(args.pdb).expanduser().resolve()
    native_info_path = Path(args.native_info).expanduser()
    work_dir = enter_work_dir(args.work_dir, config)
    if not native_info_path.is_absolute():
        native_info_path = work_dir / native_info_path

    box_cfg = config.get("box", {})
    if args.center:
        center = np.asarray(args.center, dtype=float)
        default_size = float(get_config(config, "box.min_size", 22.0))
        sizes = np.asarray(args.size or [default_size] * 3, dtype=float)
        source = "explicit"
    else:
        residue_name, chain, residue_id = read_native_info(native_info_path)
        coordinates = ligand_coordinates(
            pdb_path, residue_name, chain, residue_id
        )
        center, sizes = calculate_box(
            coordinates,
            float(box_cfg.get("padding", 8.0)),
            float(box_cfg.get("min_size", 22.0)),
            float(box_cfg.get("max_size", 30.0)),
        )
        source = f"{residue_name}:{chain}:{residue_id}"

    output = Path(args.output)
    if not output.is_absolute():
        output = work_dir / output
    write_vina_config(
        output,
        args.receptor,
        args.ligand,
        center,
        sizes,
        config.get("docking", {}),
    )
    result = {
        "output": str(output),
        "source": source,
        "center": [round(float(value), 3) for value in center],
        "size": [round(float(value), 1) for value in sizes],
    }
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"Created {output}")
        print(f"  Source: {source}")
        print(f"  Center: {result['center']}")
        print(f"  Size:   {result['size']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
